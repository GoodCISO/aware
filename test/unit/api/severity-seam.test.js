test('PRECONDITION: the payload actually reaches the component (no vacuous pass)', () => {
  // Every assertion below is satisfied by an EMPTY anomaly list -- all counts
  // are 0 and no colour appears. That is exactly the broken state, so the
  // suite must prove it is looking at real data before it proves anything else.
  const html = renderAlerts([
    { id: 'probe', severity: 'CRITICAL', description: 'probe', detectedAt: '2026-01-01T00:00:00Z' },
  ]);
  assert.ok(html.length > 1000, 'the component rendered suspiciously little markup');
  assert.ok(html.includes('probe'), 'the probe anomaly did not reach the markup');
});

test('the server emits canonical severities the UI recognises', async () => {
  const payload = await getJson('/api/anomalies');
  assert.ok(Array.isArray(payload) && payload.length > 0, 'expected a non-empty anomaly payload');

  for (const anomaly of payload) {
    assert.ok(
      isCanonicalSeverity(anomaly.severity),
      `${anomaly.id} carries non-canonical severity ${JSON.stringify(anomaly.severity)} on the wire`,
    );
    // The UI has its OWN copy of the contract (it cannot import the CJS one
    // across the react-scripts module boundary). Both must accept the same
    // value, or the boundary is exactly where the two halves disagree.
    assert.equal(
      normalizeSeverity(anomaly.severity),
      normalizeSeverityServer(anomaly.severity),
      `UI and server contracts disagree on ${JSON.stringify(anomaly.severity)}`,
    );
  }
});

test('SEAM: every severity on the wire renders as a DISTINCT colour token', async () => {
  const payload = await getJson('/api/anomalies');
  const html = renderAlerts(payload);

  const rendered = [...new Set(severityTokensIn(html))];
  const present = [...new Set(payload.map((a) => a.severity))];

  // Pre-fix this was the whole bug: all three server severities fell through
  // the component's `default:` branch and every card emitted `info.main`.
  assert.ok(rendered.length > 0, 'no severity token reached the markup at all');
  assert.deepEqual(
    rendered.filter((t) => !SEVERITY_LEVELS.includes(t)),
    [],
    `markup references severity tokens outside the enum: ${rendered.join(', ')}`,
  );

  // The colours themselves must be distinct, not just the token names.
  const colours = present.map((s) => SEVERITY_RAMP[normalizeSeverity(s)]);
  assert.equal(
    new Set(colours).size,
    colours.length,
    `severities ${JSON.stringify(present)} collapse onto ${JSON.stringify(colours)}`,
  );

  // And every severity the server actually sends must have reached a card --
  // this is the assertion that failed for nine days.
  for (const severity of present) {
    assert.ok(
      rendered.includes(normalizeSeverity(severity)),
      `${severity} is on the wire but no card rendered a severity.${severity} token; ` +
      `markup only had ${JSON.stringify(rendered)}`,
    );
  }
});

test('SEAM: every stat counter is non-zero for every severity on the wire', async () => {
  const payload = await getJson('/api/anomalies');
  const html = renderAlerts(payload);
  const cards = statCardsIn(html);

  const present = [...new Set(payload.map((a) => a.severity))];
  assert.ok(present.length >= 1, 'no severities to count');

  for (const level of present) {
    assert.ok(level in cards, `no stat card rendered for ${level}`);
    assert.equal(
      cards[level],
      payload.filter((a) => a.severity === level).length,
      `stat card for ${level} read ${cards[level]}; the payload contains ` +
      `${payload.filter((a) => a.severity === level).length}`,
    );
    // The pre-fix defect in its purest form: the counter was correct
    // arithmetic against a vocabulary nothing was ever counted in, so it
    // rendered 0 next to a real anomaly.
    assert.ok(cards[level] > 0, `stat counter for ${level} rendered 0 while the payload contains it`);
  }
});

test('SEAM: the tab set is derived from the enum, and every tab has a reachable anomaly', async () => {
  const payload = await getJson('/api/anomalies');
  const html = renderAlerts(payload);

  // One tab per canonical level plus All. Pre-fix this was a hardcoded
  // critical/warning/info set, which could not name a 4-level ramp at all.
  for (const level of SEVERITY_LEVELS) {
    const expected = payload.filter((a) => a.severity === level).length;
    const tabLabel = `${level} (${expected})`;
    assert.ok(
      html.includes(tabLabel),
      `no tab labelled ${JSON.stringify(tabLabel)}; a severity tab that matches nothing ` +
      'is an unreachable anomaly',
    );
  }
  assert.ok(
    html.includes(`All (${payload.length})`),
    `the All tab must account for all ${payload.length} anomalies`,
  );
});

test('SEAM: a legacy-vocabulary payload still renders (older deploys must degrade, not blank)', () => {
  // The component normalises at the render boundary precisely so a payload
  // from an older deploy cannot reintroduce the original defect. This asserts
  // that path still works: the OLD vocabulary is coerced, not dropped and not
  // rendered as a wrong colour.
  const html = renderAlerts([
    { id: 'l1', severity: 'high', description: 'legacy high', detectedAt: '2026-01-01T00:00:00Z' },
    { id: 'l2', severity: 'warning', description: 'legacy warning', detectedAt: '2026-01-01T00:00:00Z' },
    { id: 'l3', severity: 'critical', description: 'legacy critical', detectedAt: '2026-01-01T00:00:00Z' },
  ]);
  assert.ok(html.includes('legacy high'), 'a legacy-severity anomaly was dropped from the list');
  // 'high' -> HIGH, 'warning' -> MEDIUM, 'critical' -> CRITICAL per the
  // contract's alias table. Each must appear as a canonical label.
  for (const level of ['CRITICAL', 'HIGH', 'MEDIUM']) {
    assert.ok(
      html.includes(`severity.${level}`),
      `legacy severity did not map onto severity.${level}`,
    );
  }
});

test('GUARD: the component imports the contract instead of hardcoding a vocabulary', () => {
  // A source-level check, deliberately in addition to the render assertions:
  // it pins the MECHANISM, so a future refactor that re-inlines a literal
  // switch cannot pass merely because the current seed data happens to agree.
  const src = fs.readFileSync(
    path.join(UI_DIR, 'src/components/AnomalyDetectionAlerts.js'),
    'utf8',
  );
  const code = src.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

  assert.match(code, /from\s+'\.\.\/constants\/severity'/,
    'the component must import the canonical severity contract');
  // The pre-fix literals. Their return would be a component that cannot read
  // the API's vocabulary, which is the original defect.
  for (const legacy of ["'warning'", "'info'", "'low'", "'medium'", "'high'"]) {
    assert.ok(
      !code.includes(`=== ${legacy}`),
      `component still compares severity === ${legacy}; a lowercase predicate matches ` +
      'nothing against canonical UPPERCASE data and reports 0',
    );
  }
});

test('GUARD: the container no longer masks the defect with a same-vocabulary fixture', () => {
  // The masking mechanism, pinned. AnomalyDetectionContainer.js used to
  // render mockAnomalies carrying 'warning'/'critical' -- the COMPONENT's own
  // vocabulary -- from its `catch` branch, so the panel rendered correctly
  // only when the request failed. The live payload took the broken path for
  // nine days while the fixture demonstrated the good one.
  const src = fs.readFileSync(
    path.join(UI_DIR, 'src/containers/AnomalyDetectionContainer.js'),
    'utf8',
  );
  const code = src.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

  for (const legacy of ["severity: 'warning'", "severity: 'critical'"]) {
    assert.ok(
      !code.includes(legacy),
      `the offline fixture still hardcodes ${legacy}; that vocabulary is not the API's`,
    );
  }
  // And the fallback must be announced rather than silently plausible.
  assert.match(code, /setError\(/,
    'a failed load must set an error state; silently swapping in placeholder data ' +
    'is what hid this defect');
  assert.match(code, /placeholder data, not detected anomalies|<Alert/,
    'the offline state must be visibly labelled as placeholder data');
});

test('GUARD: the server has no legacy severity predicate left', () => {
  // /api/anomalies/stats and /api/dashboard/summary both compared against
  // 'high' and silently reported 0 once the enum moved. Comments are stripped
  // first: a guard that bans documenting the bug it prevents gets deleted.
  const source = fs.readFileSync(path.join(__dirname, '../../../src/server.js'), 'utf8');
  const code = source.split('\n').filter((line) => !line.trim().startsWith('//')).join('\n');
  const offenders = [...code.matchAll(/severity\s*===\s*'([^']*)'/g)]
    .map((m) => m[1])
    .filter((v) => !SEVERITY_LEVELS.includes(v));
  assert.deepEqual(offenders, [],
    `src/server.js still compares severity against non-canonical literal(s): ${offenders.join(', ')}`);
});

test('GUARD: the seed literals are canonical AT SOURCE, not only after coercion', () => {
  // server.js normalises the seed array at load time. That coercion MASKS
  // drift: with the literals reverted to 'high'/'medium'/'low' and the
  // normaliser left in place, every API-level assertion above still passes,
  // because the boundary repairs the value before any consumer sees it. The
  // literals are therefore checked where the drift is visible.
  const source = fs.readFileSync(path.join(__dirname, '../../../src/server.js'), 'utf8');
  const start = source.indexOf('const anomalies = [');
  const seedBlock = source.slice(start, source.indexOf('];', start));
  assert.ok(seedBlock.length > 0, 'could not locate the seed array in src/server.js');

  const literals = [...seedBlock.matchAll(/severity:\s*'([^']+)'/g)].map((m) => m[1]);
  assert.ok(literals.length >= 4, `expected >=4 seed severities, found ${literals.length}`);
  for (const literal of literals) {
    assert.ok(
      isCanonicalSeverity(literal) && literal === literal.toUpperCase(),
      `src/server.js seed literal severity '${literal}' is not canonical UPPERCASE. The ` +
      'load-time normaliser would silently repair it, hiding the drift.',
    );
  }
});

test('GUARD: the seed exercises the top of the ladder, so CRITICAL cannot report 0 silently', () => {
  // Precondition for every "critical > 0" claim anywhere in this suite. With
  // no CRITICAL record, a broken CRITICAL predicate compares 0 to 0 and
  // passes -- which is how the original fix could be marked done.
  const source = fs.readFileSync(path.join(__dirname, '../../../src/server.js'), 'utf8');
  const start = source.indexOf('const anomalies = [');
  const seedBlock = source.slice(start, source.indexOf('];', start));
  assert.ok(
    /severity:\s*'CRITICAL'/.test(seedBlock),
    'the seed data must contain a CRITICAL anomaly, or the top of the ladder is untested',
  );
});

test('stats.critical means CRITICAL-and-unacknowledged, not CRITICAL-with-HIGH-and-ack folded in', async () => {
  const stats = await getJson('/api/anomalies/stats');
  const payload = await getJson('/api/anomalies');

  // Non-vacuity first: without an unacknowledged CRITICAL this is 0 === 0.
  const trueCritical = payload.filter((a) => a.severity === 'CRITICAL' && !a.acknowledged).length;
  assert.ok(trueCritical > 0, 'expected at least one unacknowledged CRITICAL anomaly in the seed');
  assert.equal(stats.critical, trueCritical);

  // bySeverity must sum to the payload -- a level silently missing from the
  // breakdown is how "3 severities render as 1 colour" starts.
  const sum = SEVERITY_LEVELS.reduce((acc, l) => acc + stats.bySeverity[l], 0);
  assert.equal(sum, payload.length, 'bySeverity buckets must account for every anomaly');
  assert.equal(stats.acknowledged + stats.unacknowledged, stats.total);
});

test('the dashboard summary counts the same CRITICAL records the stats route does', async () => {
  const summary = await getJson('/api/dashboard/summary');
  const payload = await getJson('/api/anomalies');
  const expected = payload.filter((a) => a.severity === 'CRITICAL' && !a.acknowledged).length;
  // Both routes compared against 'high' before the fix and both reported 0.
  assert.ok(expected > 0, 'expected a non-zero CRITICAL baseline for this assertion to bite');
  assert.equal(summary.criticalAlerts, expected);
});

test('an anomaly detail lookup returns a canonical severity too', async () => {
  const payload = await getJson('/api/anomalies');
  const detail = await getJson(`/api/anomalies/${payload[0].id}`);
  assert.equal(detail.id, payload[0].id);
  assert.ok(isCanonicalSeverity(detail.severity));
});

test('module hygiene: the harness loads real modules, not fixtures', () => {
  // Preconditions for every assertion above. If these drift, the suite could
  // pass while rendering a hand-written double -- the P125 trap.
  assert.equal(typeof AnomalyDetectionAlerts, 'function',
    'the real component was not loaded; the render assertions would be vacuous');
  assert.equal(typeof renderToStaticMarkup, 'function');
  assert.equal(SEVERITY_LEVELS.length, 4, 'the canonical enum must have 4 levels');
  assert.equal(new Set(Object.values(SEVERITY_RAMP)).size, 4,
    'the ramp must have 4 distinct colours for the distinctness assertion to bite');
  assert.equal(AnomalyDetectionAlerts, loadUiModule('components/AnomalyDetectionAlerts.js').default,
    'the component must be the real module, freshly loaded');
});
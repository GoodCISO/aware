/**
 * The seam guard: does the SERVER EMIT what the UI CONSUMES?
 *
 * Card t_775073b4. The product carried four incompatible severity
 * vocabularies and the UI was bound to none of them. Every anomaly therefore
 * fell through the component's switch `default`: three severities rendered as
 * one colour, every stat counter read 0, and no anomaly was reachable under
 * any severity tab.
 *
 * WHY THIS FILE EXISTS AND WHY IT IS NOT ANOTHER MODULE-IN-ISOLATION TEST.
 * The tree shipped three green guards that could not see any of this:
 *
 *   test/unit/monitoring/severity-contract.test.js   13/13 PASS
 *   test/unit/ui/token-literals.test.js               7/7 PASS
 *   test/unit/ui/severity-ramp.test.js                9/9 PASS
 *
 * All three exercise a token or contract module on its own. None asserts that
 * the server emits contract values, and none asserts that the component
 * consumes them. A suite that only ever tests each part against itself is
 * green on a tree where the two halves are wired to different languages. That
 * is why a fix was marked `done` on 2026-09-30 (t_517be819) and the defect was
 * still live nine days later: the branch that held the fix was never merged,
 * and nothing that ran on main could tell.
 *
 * So this file crosses the seam for real:
 *
 *   1. boots the REAL express app from src/server.js on an ephemeral port,
 *   2. fetches the REAL /api/anomalies payload over HTTP,
 *   3. feeds that payload to the REAL AnomalyDetectionAlerts component,
 *   4. renders it with react-dom/server, and
 *   5. asserts on the resulting markup -- distinct colours, non-zero
 *      counters, and a reachable anomaly under every severity tab.
 *
 * Nothing here is stubbed. The payload that fails an assertion is the payload
 * a browser would have received.
 *
 * The renderer is react-dom/server (renderToStaticMarkup), not a DOM: it needs
 * no jsdom and no browser, and it produces the same element tree. That is
 * sufficient because every property under test -- which colour token a card
 * resolves to, what a counter renders, what a tab is labelled -- is decided
 * during render and lands in the markup. Nothing under test depends on
 * post-mount effects.
 *
 * SCOPE, stated rather than implied: the severity Tabs are controlled
 * component state (`value={filter}`), and this harness asserts on the tab
 * LABELS and COUNTS that render, not on the post-click filtered list. Reach
 * is therefore established the way a user reaches it -- every anomaly the
 * server sent is counted under a tab whose label names it -- while the
 * `filter === level` comparison inside the component remains covered by the
 * mechanism guard below (the component must derive the tab set and the
 * counters from the same enum). Driving the actual tab click would need a
 * DOM renderer; that is not bought here, and the gap is named rather than
 * papered over.
 */

'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const { execFileSync } = require('node:child_process');

// --- Load the real UI modules through the babel bridge -----------------------
// The component is ESM + JSX, so plain Node cannot require it. helpers/
// ui-real-module.js transforms it in memory and keeps node_modules resolution
// pointed at src/ui, where react and @mui/material actually live. It fails
// loudly rather than silently degrading to a source scan -- a fallback to
// grep is precisely the failure mode this file exists to end.
const { loadUiModule, UI_DIR } = require('../helpers/ui-real-module');

const React = require(path.join(UI_DIR, 'node_modules/react'));
const { renderToStaticMarkup } = require(path.join(UI_DIR, 'node_modules/react-dom/server'));

const AnomalyDetectionAlerts = loadUiModule('components/AnomalyDetectionAlerts.js').default;
const { SEVERITY_LEVELS, normalizeSeverity } = loadUiModule('constants/severity.js');
const { SEVERITY_RAMP } = loadUiModule('styles/severityRamp.js');
const { normalizeSeverity: normalizeSeverityServer, isCanonicalSeverity } =
  require('../../../src/monitoring/severity-contract');

// --- Load the real server ----------------------------------------------------
// src/server.js reads src/data/{agents,users}.json at require time and those
// outputs are GITIGNORED (generated by scripts/seed-dev-*.js at install), so a
// fresh clone or a git worktree cannot require the server until they have run.
// Provision them here rather than depending on local state that neither CI nor
// a new worktree will have. Mirrors the documented install-time pattern.
const DATA_DIR = path.join(__dirname, '../../../src/data');
for (const [file, seeder] of [['agents.json', 'seed-dev-agents.js'], ['users.json', 'seed-dev-users.js']]) {
  if (!fs.existsSync(path.join(DATA_DIR, file))) {
    execFileSync(process.execPath, [path.join(__dirname, '../../../scripts', seeder)], { stdio: 'ignore' });
  }
}

const { app } = require('../../../src/server');

let server;
let baseUrl;

const getJson = async (route) => {
  const res = await fetch(`${baseUrl}${route}`);
  assert.equal(res.status, 200, `${route} returned ${res.status}`);
  return res.json();
};

test.before(async () => {
  await new Promise((resolve) => { server = app.listen(0, '127.0.0.1', resolve); });
  baseUrl = `http://127.0.0.1:${server.address().port}`;
});

test.after(async () => {
  if (server) await new Promise((resolve) => server.close(resolve));
});

// ---------------------------------------------------------------------------
// Render helpers -- these drive the REAL component, they do not restate it.
// ---------------------------------------------------------------------------

const renderAlerts = (anomalies) =>
  renderToStaticMarkup(React.createElement(AnomalyDetectionAlerts, { anomalies }));

/** Every `severity.<LEVEL>` token reference in the markup. */
const severityTokensIn = (html) => [...html.matchAll(/severity\.([A-Z]+)/g)].map((m) => m[1]);

/** The stat cards render `<h3 class="...">N</h3><...>LEVEL</...>`; pull level->count. */
const statCardsIn = (html) => {
  const out = {};
  for (const level of SEVERITY_LEVELS) {
    // MUI renders the Typography variant as a class containing the variant
    // name; match the count that immediately precedes the level label.
    const re = new RegExp(`MuiTypography-h3[^>]*>([^<]*)</[^>]+>[^<]*<[^>]*>${level}<`);
    const m = html.match(re);
    if (m) out[level] = Number(m[1]);
  }
  return out;
};

